CREATE TABLE USERS (
    USERID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRSTNAME VARCHAR2(100),
    LASTNAME VARCHAR2(100),
    EMAIL VARCHAR2(255),
    DOB DATE,
    GENDER VARCHAR2(20),
    PASSWORD VARCHAR2(255)
);

CREATE TABLE ACHIEVEMENT (
    ACHIEVEMENTID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(200),
    DESCRIPTION VARCHAR2(1000),
    DATEAWARDED DATE
);

CREATE TABLE ACTIVITY (
    ACTIVITYID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TYPE VARCHAR2(100),
    DURATION NUMBER,
    DISTANCE NUMBER,
    "Date" DATE,
    USERID NUMBER,
    CONSTRAINT FK_ACTIVITY_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID)
);

CREATE TABLE ATHLETE (
    USERID NUMBER PRIMARY KEY,
    SPORTTYPE VARCHAR2(100),
    SKILLLEVEL VARCHAR2(50),
    CONSTRAINT FK_ATHLETE_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID)
);

CREATE TABLE TRAINER (
    USERID NUMBER PRIMARY KEY,
    CERTIFICATIONNO VARCHAR2(100),
    YEARSEXPERIENCE NUMBER,
    CONSTRAINT FK_TRAINER_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID)
);

CREATE TABLE USER_PHONE (
    USERID NUMBER,
    PHONENUMBER VARCHAR2(20),
    CONSTRAINT PK_USER_PHONE PRIMARY KEY (USERID, PHONENUMBER),
    CONSTRAINT FK_PHONE_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID)
);

CREATE TABLE WEARABLE_DEVICE (
    DEVICEID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BRAND VARCHAR2(100),
    MODEL VARCHAR2(100),
    SERIALNUMBER VARCHAR2(100),
    USERID NUMBER,
    CONSTRAINT FK_DEVICE_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID)
);

CREATE TABLE DEVICE_FEATURE (
    DEVICEID NUMBER,
    FEATURENAME VARCHAR2(200),
    CONSTRAINT PK_DEVICE_FEATURE PRIMARY KEY (DEVICEID, FEATURENAME),
    CONSTRAINT FK_FEATURE_DEVICE
        FOREIGN KEY (DEVICEID) REFERENCES WEARABLE_DEVICE(DEVICEID)
);

CREATE TABLE FITNESS_BAND (
    DEVICEID NUMBER PRIMARY KEY,
    BANDMATERIAL VARCHAR2(100),
    HASHRSENSOR VARCHAR2(10),
    CONSTRAINT FK_FITNESS_BAND_DEVICE
        FOREIGN KEY (DEVICEID) REFERENCES WEARABLE_DEVICE(DEVICEID)
);

CREATE TABLE SMARTWATCH (
    DEVICEID NUMBER PRIMARY KEY,
    HASGPS VARCHAR2(10),
    WATERRESISTANCE VARCHAR2(100),
    CONSTRAINT FK_SMARTWATCH_DEVICE
        FOREIGN KEY (DEVICEID) REFERENCES WEARABLE_DEVICE(DEVICEID)
);

CREATE TABLE HEALTH_METRIC (
    DEVICEID NUMBER,
    METRICID NUMBER PRIMARY KEY,
    METRICTYPE VARCHAR2(100),
    VALUE NUMBER(12,2),
    UNIT VARCHAR2(50),
    "TIMESTAMP" TIMESTAMP(6),
    CONSTRAINT FK_METRIC_DEVICE
        FOREIGN KEY (DEVICEID) REFERENCES WEARABLE_DEVICE(DEVICEID)
);

CREATE TABLE GOAL (
    GOALID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GOALTYPE VARCHAR2(100),
    TARGETVALUE NUMBER(12,2),
    DEADLINE DATE,
    USERID NUMBER,
    CONSTRAINT FK_GOAL_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID)
);

CREATE TABLE NUTRITION (
    NUTRITIONID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MEALTYPE VARCHAR2(100),
    CALORIES NUMBER(10,2),
    QUANTITY NUMBER(10,2),
    "Date" DATE,
    USERID NUMBER,
    CONSTRAINT FK_NUTRITION_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID)
);

CREATE TABLE NUTRITION_FOODITEM (
    NUTRITIONID NUMBER,
    FOODITEM VARCHAR2(200),
    CONSTRAINT PK_NUTRITION_FOODITEM
        PRIMARY KEY (NUTRITIONID, FOODITEM),
    CONSTRAINT FK_FOODITEM_NUTRITION
        FOREIGN KEY (NUTRITIONID) REFERENCES NUTRITION(NUTRITIONID)
);

CREATE TABLE NOTIFICATION_RECIPIENT (
    RECIPIENTID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCETYPE VARCHAR2(100),
    USERID NUMBER,
    TRAINERUSERID NUMBER,
    CONTACTCHANNEL VARCHAR2(100),
    NOTIFICATIONPREF VARCHAR2(100),
    CONSTRAINT FK_NOTIFICATION_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID),
    CONSTRAINT FK_NOTIFICATION_TRAINER
        FOREIGN KEY (TRAINERUSERID) REFERENCES TRAINER(USERID)
);

CREATE TABLE SUPERVISION (
    TRAINERID NUMBER,
    USERID NUMBER,
    ACTIVITYID NUMBER,
    SESSIONNOTES VARCHAR2(500),
    PERFORMANCERATING NUMBER(5,2),
    CONSTRAINT PK_SUPERVISION
        PRIMARY KEY (TRAINERID, USERID, ACTIVITYID),
    CONSTRAINT FK_SUPERVISION_TRAINER
        FOREIGN KEY (TRAINERID) REFERENCES TRAINER(USERID),
    CONSTRAINT FK_SUPERVISION_USER
        FOREIGN KEY (USERID) REFERENCES USERS(USERID),
    CONSTRAINT FK_SUPERVISION_ACTIVITY
        FOREIGN KEY (ACTIVITYID) REFERENCES ACTIVITY(ACTIVITYID)
);

CREATE TABLE EARNS (
    ACTIVITYID NUMBER,
    ACHIEVEMENTID NUMBER,
    CONSTRAINT PK_EARNS
        PRIMARY KEY (ACTIVITYID, ACHIEVEMENTID),
    CONSTRAINT FK_EARNS_ACTIVITY
        FOREIGN KEY (ACTIVITYID) REFERENCES ACTIVITY(ACTIVITYID),
    CONSTRAINT FK_EARNS_ACHIEVEMENT
        FOREIGN KEY (ACHIEVEMENTID) REFERENCES ACHIEVEMENT(ACHIEVEMENTID)
);

CREATE TABLE USER_FOLLOWS (
    FOLLOWERID NUMBER,
    FOLLOWEEID NUMBER,
    CONSTRAINT PK_USER_FOLLOWS
        PRIMARY KEY (FOLLOWERID, FOLLOWEEID),
    CONSTRAINT FK_FOLLOWER_USER
        FOREIGN KEY (FOLLOWERID) REFERENCES USERS(USERID),
    CONSTRAINT FK_FOLLOWEE_USER
        FOREIGN KEY (FOLLOWEEID) REFERENCES USERS(USERID)
);
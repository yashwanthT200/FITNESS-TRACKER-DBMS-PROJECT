ALTER SESSION SET CONTAINER = FREEPDB1;

DECLARE
    user_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO user_count
    FROM DBA_USERS
    WHERE USERNAME = 'GARMIN_USER';

    IF user_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER GARMIN_USER IDENTIFIED BY GarminDocker123';
    ELSE
        EXECUTE IMMEDIATE 'ALTER USER GARMIN_USER IDENTIFIED BY GarminDocker123 ACCOUNT UNLOCK';
    END IF;

    EXECUTE IMMEDIATE 'ALTER USER GARMIN_USER ACCOUNT UNLOCK';

    EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO GARMIN_USER';
    EXECUTE IMMEDIATE 'GRANT CREATE TABLE TO GARMIN_USER';
    EXECUTE IMMEDIATE 'GRANT CREATE VIEW TO GARMIN_USER';
    EXECUTE IMMEDIATE 'GRANT CREATE SEQUENCE TO GARMIN_USER';
    EXECUTE IMMEDIATE 'GRANT CREATE PROCEDURE TO GARMIN_USER';
    EXECUTE IMMEDIATE 'GRANT CREATE TRIGGER TO GARMIN_USER';

    EXECUTE IMMEDIATE 'ALTER USER GARMIN_USER QUOTA UNLIMITED ON USERS';
END;
/